    def get(self, run_id: str) -> StoredRun | None:
        with _redacted("load run"), self._connection() as connection:
            row = connection.execute(
                "SELECT r.status, r.result_content_hash, r.run_record_hash, s.content_sha256"
                " FROM scenario_run r JOIN input_snapshot s ON s.id = r.input_snapshot_id"
                " WHERE r.id = ?",
                (run_id,),
            ).fetchone()
            if row is None:
                return None
            stages = tuple(
                {
                    "stage_code": str(stage["stage_code"]),
                    "stage_ordinal": int(stage["stage_ordinal"]),
                    "status": str(stage["status"]),
                    "row_count": int(stage["produced_row_count"]),
                }
                for stage in connection.execute(
                    "SELECT stage_code, stage_ordinal, status, produced_row_count FROM run_stage"
                    " WHERE run_id = ? ORDER BY stage_ordinal",
                    (run_id,),
                ).fetchall()
            )
            return StoredRun(
                run_id=run_id,
                status=str(row["status"]),
                input_snapshot_hash=str(row["content_sha256"]),
                result_content_hash=str(row["result_content_hash"]),
                run_record_hash=str(row["run_record_hash"]),
                stages=stages,
                result=self._read_document(connection, run_id, str(row["result_content_hash"])),
                persisted_rows=self._read_rows(connection, run_id),
            )

    @staticmethod
    def _read_document(
        connection: sqlite3.Connection, run_id: str, expected_hash: str
    ) -> dict[str, Any]:
        row = connection.execute(
            "SELECT content_sha256, document FROM run_result_document WHERE run_id = ?",
            (run_id,),
        ).fetchone()
        if row is None:  # pragma: no cover - every stored run writes its document
            return {}
        if str(row["content_sha256"]) != expected_hash:
            raise SqlitePersistenceError(
                "the stored result document does not match the run's result content hash"
            )
        loaded: dict[str, Any] = json.loads(str(row["document"]))
        return loaded

    def _read_rows(self, connection: sqlite3.Connection, run_id: str) -> PersistedRows:
        results = connection.execute(
            "SELECT id, stable_key, result_kind, calculation_status, decision_grade"
            " FROM run_result WHERE run_id = ?",
            (run_id,),
        ).fetchall()
        key_of = {str(row["id"]): str(row["stable_key"]) for row in results}
        station_key = self._lookup(connection, "scenario_station")
        payload_key = self._lookup(connection, "scenario_payload")

        def fetch(statement: str) -> Sequence[sqlite3.Row]:
            return connection.execute(statement, (run_id,)).fetchall()

        geometric = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "station_key": station_key[str(row["scenario_station_id"])],
                "true_aos": _iso(row["true_aos_us"]),
                "true_los": _iso(row["true_los_us"]),
                "clipped_start": _iso(row["clipped_start_us"]),
                "clipped_end": _iso(row["clipped_end_us"]),
                "maximum_elevation_udeg": _int(row["maximum_elevation_udeg"]),
                "maximum_elevation_at": _iso(row["maximum_elevation_at_us"]),
                "contact_source": str(row["contact_source"]),
            }
            for row in fetch(
                "SELECT g.* FROM geometric_access g JOIN run_result r ON r.id = g.result_id"
                " WHERE r.run_id = ?"
            )
        )
        modeled = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "geometric_stable_key": key_of[str(row["geometric_result_id"])],
                "link_compatibility": str(row["link_compatibility"]),
                "usable_start": _iso(row["usable_start_us"]),
                "usable_end": _iso(row["usable_end_us"]),
                "primary_reason_code": row["primary_reason_code"],
            }
            for row in fetch(
                "SELECT m.* FROM modeled_contact m JOIN run_result r ON r.id = m.result_id"
                " WHERE r.run_id = ?"
            )
        )
        candidates = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "modeled_stable_key": key_of[str(row["modeled_contact_result_id"])],
                "capacity_bytes": _int(row["capacity_bytes"]),
                "conflict_component_key": row["conflict_component_key"],
            }
            for row in fetch(
                "SELECT c.* FROM candidate_session c JOIN run_result r ON r.id = c.result_id"
                " WHERE r.run_id = ?"
            )
        )
        scheduled = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "candidate_stable_key": key_of[str(row["candidate_result_id"])],
                "selection_ordinal": int(row["selection_ordinal"]),
                "primary_reason_code": str(row["primary_reason_code"]),
            }
            for row in fetch(
                "SELECT s.* FROM scheduled_session s JOIN run_result r ON r.id = s.result_id"
                " WHERE r.run_id = ?"
            )
        )
        allocations = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "scheduled_session_stable_key": key_of[str(row["scheduled_session_result_id"])],
                "payload_key": payload_key[str(row["scenario_payload_id"])],
                "allocation_ordinal": int(row["allocation_ordinal"]),
                "logical_offset_start": int(row["logical_offset_start"]),
                "logical_bytes": int(row["logical_bytes"]),
                "started_at": _iso(row["started_at_us"]),
                "ended_at": _iso(row["ended_at_us"]),
                "modeled_progress_after_bytes": int(row["modeled_progress_after_bytes"]),
                "modeled_tx_complete_at": _iso(row["modeled_tx_complete_at_us"]),
                "deadline_status": row["deadline_status"],
                "remaining_after_bytes": int(row["remaining_after_bytes"]),
                "primary_reason_code": str(row["primary_reason_code"]),
            }
            for row in fetch(
                "SELECT t.* FROM transfer_allocation t JOIN run_result r ON r.id = t.result_id"
                " WHERE r.run_id = ?"
            )
        )
        events = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "event_at": _iso(row["event_at_us"]),
                "event_order": int(row["event_order"]),
                "event_domain": str(row["event_domain"]),
                "event_kind": str(row["event_kind"]),
                "payload_key": (
                    payload_key[str(row["scenario_payload_id"])]
                    if row["scenario_payload_id"]
                    else None
                ),
                "allocation_stable_key": (
                    key_of[str(row["allocation_result_id"])]
                    if row["allocation_result_id"]
                    else None
                ),
                "delta_logical_bytes": _int(row["delta_logical_bytes"]),
                "remaining_logical_bytes": _int(row["remaining_logical_bytes"]),
                "delta_storage_bytes": _int(row["delta_storage_bytes"]),
                "occupancy_bytes": _int(row["occupancy_bytes"]),
                "reserve_breach_bytes": _int(row["reserve_breach_bytes"]),
                "rejected_bytes": _int(row["rejected_bytes"]),
                "reason_code": str(row["reason_code"]),
            }
            for row in fetch("SELECT * FROM run_event WHERE run_id = ?")
        )
        metrics = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "metric_code": str(row["metric_code"]),
                "scope_code": str(row["scope_code"]),
                "station_key": (
                    station_key[str(row["scenario_station_id"])]
                    if row["scenario_station_id"]
                    else None
                ),
                "payload_key": (
                    payload_key[str(row["scenario_payload_id"])]
                    if row["scenario_payload_id"]
                    else None
                ),
                "unit_code": str(row["unit_code"]),
                "definition_revision": str(row["definition_revision"]),
                "accounting_layer": row["accounting_layer"],
                "value_integer": _int(row["value_integer"]),
            }
            for row in fetch(
                "SELECT m.* FROM run_metric m JOIN run_result r ON r.id = m.result_id"
                " WHERE r.run_id = ?"
            )
        )
        annotations = tuple(
            {
                "stable_key": key_of[str(row["result_id"])],
                "subject_stable_key": (
                    key_of[str(row["subject_result_id"])] if row["subject_result_id"] else None
                ),
                "annotation_kind": str(row["annotation_kind"]),
                "code": str(row["code"]),
                "severity": str(row["severity"]),
                "ordinal": int(row["ordinal"]),
                "rule_revision": str(row["rule_revision"]),
                "criterion_code": row["criterion_code"],
                "criterion_value_text": row["criterion_value_text"],
            }
            for row in fetch(
                "SELECT a.* FROM run_annotation a JOIN run_result r ON r.id = a.result_id"
                " WHERE r.run_id = ?"
            )
        )
        return PersistedRows(
            results=tuple(
                {
                    "stable_key": str(row["stable_key"]),
                    "result_kind": str(row["result_kind"]),
                    "calculation_status": str(row["calculation_status"]),
                    "decision_grade": (
                        str(row["decision_grade"]) if row["decision_grade"] is not None else None
                    ),
                }
                for row in results
            ),
            geometric=geometric,
            modeled=modeled,
            candidates=candidates,
            scheduled=scheduled,
            allocations=allocations,
            events=events,
            metrics=metrics,
            annotations=annotations,
        )

    @staticmethod
    def _lookup(connection: sqlite3.Connection, table: str) -> dict[str, str]:
        statement = {
            "scenario_station": "SELECT id, stable_key FROM scenario_station",
            "scenario_payload": "SELECT id, stable_key FROM scenario_payload",
        }[table]
        return {
            str(row["id"]): str(row["stable_key"])
            for row in connection.execute(statement).fetchall()
        }

