def test_a_service_without_an_orbit_provider_refuses_orbit_derived() -> None:
    """No fallback to the synthetic provider (ADR-0004): a misconfigured deployment fails loudly."""
    service = RunScenarioService(SyntheticContactProvider(), InMemoryRunRepository())
    snapshot = load_fixture_source(FIXTURE).to_domain()
    try:
        service.run(snapshot)
    except Exception as exc:
        assert "ORBIT_PROVIDER_NOT_CONFIGURED" in str(type(exc)) or "orbit provider" in str(exc)
    else:  # pragma: no cover - the run must not succeed without an orbit provider
        raise AssertionError("a service with no orbit provider must refuse ORBIT_DERIVED")


def test_a_user_supplied_tle_also_generates_contacts() -> None:
    """The tool lets a user try their own orbit; a TLE is request data, not a KMU claim."""
    content = _fixture_content()
    # A synthetic, self-consistent circular LEO TLE (not a real object).
    content["fixture_id"] = "PB-PROBE-TLE"
    content["orbit"] = {
        "kind": "GP_TLE",
        "tle": {
            "line_1": "1 99999U 26001A   26246.00000000  .00000000  00000+0  00000+0 0  9995",
            "line_2": "2 99999  98.0000  90.0000 0000010   0.0000   0.0000 14.90000000000010",
        },
    }
    run = _service().run(
        _content_to_snapshot(content),
    )
    assert run.result["contact_source"] == "ORBIT_DERIVED"
    assert run.result["engine_manifest"]["frame_transform_revision"] == "TEME_GMST82_TO_ITRF_V1"


def _content_to_snapshot(content: dict):  # type: ignore[no-untyped-def]
    from semantix_passbudget.interfaces.dto import parse_fixture_content

    return parse_fixture_content(copy.deepcopy(content)).to_domain()
